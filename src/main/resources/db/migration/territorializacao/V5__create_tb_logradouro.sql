CREATE TABLE tb_logradouro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bairro BIGINT REFERENCES tb_bairro(id),
    cep VARCHAR(8) NOT NULL,
    state VARCHAR(2),
    city VARCHAR(255),
    neighborhood VARCHAR(255),
    street VARCHAR(255),
    service VARCHAR(50),
    geom GEOMETRY(Geometry, 4326)
);